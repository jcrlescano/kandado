//! Turns the synced design tokens (`../resources/tokens.json`, Kandado
//! Hardware) into Rust constants, so no view hard-codes a colour or a size.
//!
//! The output is plain data with no GPUI types; `src/theme` gives it meaning.
//! Anything in the file this script does not understand stops the build:
//! a silently skipped token would show up as a wrong colour much later.

use std::{collections::BTreeMap, env, fmt::Write as _, fs, path::Path};

use serde_json::Value;

const TOKENS: &str = "../resources/tokens.json";
/// The order of every `[dark, light]` pair in the output, whatever order the
/// file declares its themes in.
const THEMES: [&str; 2] = ["dark", "light"];

fn main() {
    println!("cargo::rerun-if-changed={TOKENS}");
    println!("cargo::rerun-if-changed=build.rs");

    let text = fs::read_to_string(TOKENS)
        .unwrap_or_else(|error| panic!("{TOKENS}: {error}. Run `pnpm sync:tokens`."));
    let tokens: Value = serde_json::from_str(&text).expect("tokens.json is valid JSON");

    let mut out =
        String::from("// Generated by build.rs from resources/tokens.json. Do not edit.\n\n");
    colors(&tokens, &mut out);
    typography(&tokens, &mut out);
    lengths(&tokens, "spacing", &mut out);
    lengths(&tokens, "radius", &mut out);
    shadows(&tokens, &mut out);

    let path = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("tokens.rs");
    fs::write(path, out).expect("write tokens.rs");

    icons();
}

/// Embeds every SVG in `../resources/icons` and generates the `IconName` enum
/// from the file names, so an icon that does not exist cannot be named.
fn icons() {
    const DIR: &str = "../resources/icons";
    println!("cargo::rerun-if-changed={DIR}");

    let mut names: Vec<String> = fs::read_dir(DIR)
        .unwrap_or_else(|error| panic!("{DIR}: {error}. Run `pnpm sync:icons`."))
        .map(|entry| {
            entry
                .expect("read icons directory")
                .file_name()
                .into_string()
                .expect("UTF-8 file name")
        })
        .filter_map(|file| file.strip_suffix(".svg").map(str::to_owned))
        .collect();
    names.sort();
    assert!(
        names.iter().any(|name| name == "logo"),
        "{DIR}/logo.svg is missing. Run `pnpm sync:icons`."
    );

    let absolute = fs::canonicalize(DIR).expect("icons directory");
    let variant = |name: &str| -> String {
        name.split('-')
            .map(|part| {
                let mut letters = part.chars();
                letters
                    .next()
                    .map(|first| first.to_ascii_uppercase().to_string() + letters.as_str())
                    .unwrap_or_default()
            })
            .collect()
    };

    let mut out = String::from("// Generated by build.rs from resources/icons. Do not edit.\n\n");
    out.push_str("/// The icons of the Kandado set.\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub enum IconName {\n");
    let icons: Vec<&String> = names.iter().filter(|name| *name != "logo").collect();
    for name in &icons {
        writeln!(out, "    {},", variant(name)).unwrap();
    }
    out.push_str("}\n\nimpl IconName {\n    pub const ALL: &[IconName] = &[\n");
    for name in &icons {
        writeln!(out, "        IconName::{},", variant(name)).unwrap();
    }
    out.push_str("    ];\n\n    /// The name used in the design system, such as `eye-off`.\n    pub fn name(self) -> &'static str {\n        match self {\n");
    for name in &icons {
        writeln!(out, "            IconName::{} => {name:?},", variant(name)).unwrap();
    }
    out.push_str("        }\n    }\n\n    /// The asset path GPUI loads the icon from.\n    pub fn path(self) -> &'static str {\n        match self {\n");
    for name in &icons {
        writeln!(
            out,
            "            IconName::{} => \"kandado/icons/{name}.svg\",",
            variant(name)
        )
        .unwrap();
    }
    out.push_str("        }\n    }\n}\n\n/// The asset path of the logo mark.\npub const LOGO_PATH: &str = \"kandado/icons/logo.svg\";\n\n");
    out.push_str(
        "/// Every embedded file, by asset path.\npub(crate) const FILES: &[(&str, &[u8])] = &[\n",
    );
    for name in &names {
        let file = absolute.join(format!("{name}.svg"));
        writeln!(
            out,
            "    (\"kandado/icons/{name}.svg\", include_bytes!({:?})),",
            file.display().to_string()
        )
        .unwrap();
    }
    out.push_str("];\n");

    let path = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("icons.rs");
    fs::write(path, out).expect("write icons.rs");
}

fn list<'a>(tokens: &'a Value, group: &str, key: &str) -> &'a Vec<Value> {
    tokens[group][key]
        .as_array()
        .unwrap_or_else(|| panic!("tokens.json: {group}.{key} is not a list"))
}

fn text<'a>(value: &'a Value, what: &str) -> &'a str {
    value
        .as_str()
        .unwrap_or_else(|| panic!("tokens.json: {what} is not a string: {value}"))
}

fn ident(name: &str) -> String {
    name.replace('-', "_")
}

/// `#rrggbb` or `rgba(r, g, b, a)` as 0xRRGGBBAA.
fn rgba(css: &str) -> u32 {
    let css = css.trim();
    if let Some(hex) = css.strip_prefix('#') {
        assert_eq!(hex.len(), 6, "unsupported colour {css}");
        let rgb =
            u32::from_str_radix(hex, 16).unwrap_or_else(|_| panic!("unsupported colour {css}"));
        return rgb << 8 | 0xFF;
    }
    let inner = css
        .strip_prefix("rgba(")
        .and_then(|rest| rest.strip_suffix(')'))
        .unwrap_or_else(|| panic!("unsupported colour {css}"));
    let parts: Vec<f64> = inner
        .split(',')
        .map(|part| {
            part.trim()
                .parse()
                .unwrap_or_else(|_| panic!("unsupported colour {css}"))
        })
        .collect();
    assert_eq!(parts.len(), 4, "unsupported colour {css}");
    let channel = |value: f64| value.round().clamp(0.0, 255.0) as u32;
    channel(parts[0]) << 24
        | channel(parts[1]) << 16
        | channel(parts[2]) << 8
        | channel(parts[3] * 255.0)
}

fn px(css: &str) -> f64 {
    css.trim()
        .strip_suffix("px")
        .and_then(|number| number.parse().ok())
        .unwrap_or_else(|| panic!("unsupported length {css}"))
}

fn colors(tokens: &Value, out: &mut String) {
    let mut declared: Vec<&str> = list(tokens, "color", "themes")
        .iter()
        .map(|theme| text(&theme["id"], "theme id"))
        .collect();
    declared.sort_unstable();
    assert_eq!(
        declared, THEMES,
        "tokens.json: expected exactly the themes {THEMES:?}"
    );

    // name -> [dark, light]. Aliases such as "{teal}" point at an earlier token.
    let mut resolved: BTreeMap<String, [u32; 2]> = BTreeMap::new();
    let mut order = Vec::new();
    for token in list(tokens, "color", "tokens") {
        let name = text(&token["name"], "colour name");
        let values = match &token["value"] {
            Value::String(alias) => {
                let target = alias
                    .strip_prefix('{')
                    .and_then(|rest| rest.strip_suffix('}'))
                    .unwrap_or_else(|| {
                        panic!("tokens.json: colour {name} has unsupported value {alias}")
                    });
                *resolved.get(target).unwrap_or_else(|| {
                    panic!("tokens.json: colour {name} refers to unknown {target}")
                })
            }
            value => {
                THEMES.map(|theme| rgba(text(&value[theme], &format!("colour {name}.{theme}"))))
            }
        };
        resolved.insert(name.to_owned(), values);
        order.push(name);
    }

    out.push_str("/// Every colour of one theme, as 0xRRGGBBAA.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Palette {\n");
    for name in &order {
        writeln!(out, "    pub {}: u32,", ident(name)).unwrap();
    }
    out.push_str("}\n\n");
    for (index, (theme, doc)) in [
        ("DARK", "Graphite, the dark theme."),
        ("LIGHT", "Enamel, the light theme and the default."),
    ]
    .into_iter()
    .enumerate()
    {
        writeln!(out, "/// {doc}\npub const {theme}: Palette = Palette {{").unwrap();
        for name in &order {
            writeln!(
                out,
                "    {}: {:#010x},",
                ident(name),
                resolved[*name][index]
            )
            .unwrap();
        }
        out.push_str("};\n\n");
    }
}

fn typography(tokens: &Value, out: &mut String) {
    out.push_str(
        "/// A font family role.\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum Family {\n    Sans,\n    Mono,\n}\n\n\
         /// One text style. Sizes are in pixels; letter spacing is in ems.\n#[derive(Debug, Clone, Copy, PartialEq)]\npub struct TextToken {\n    pub family: Family,\n    pub size: f32,\n    pub line_height: f32,\n    pub weight: u16,\n    pub letter_spacing: f32,\n}\n\n",
    );

    // The first name of each CSS font stack is the bundled font.
    let roles: Vec<&String> = tokens["type"]["families"]
        .as_object()
        .expect("tokens.json: type.families is not an object")
        .keys()
        .collect();
    assert!(
        roles.len() == 2 && roles.iter().all(|role| *role == "sans" || *role == "mono"),
        "tokens.json: expected the font roles sans and mono, found {roles:?}"
    );
    for (role, constant) in [("sans", "FONT_SANS"), ("mono", "FONT_MONO")] {
        let stack = text(&tokens["type"]["families"][role], "font family");
        let first = stack
            .split(',')
            .next()
            .unwrap_or_default()
            .trim()
            .trim_matches('"');
        assert!(!first.is_empty(), "tokens.json: empty font family {role}");
        writeln!(out, "pub const {constant}: &str = {first:?};").unwrap();
    }
    out.push('\n');

    for group in list(tokens, "type", "groups") {
        let family = match text(&group["family"], "type group family") {
            "sans" => "Sans",
            "mono" => "Mono",
            other => panic!("tokens.json: unknown font family role {other}"),
        };
        for style in group["styles"].as_array().expect("type styles") {
            let name = text(&style["name"], "type style name");
            let spacing = match style.get("letterSpacing") {
                None => 0.0,
                Some(value) => text(value, "letterSpacing")
                    .strip_suffix("em")
                    .and_then(|number| number.parse::<f64>().ok())
                    .unwrap_or_else(|| panic!("tokens.json: unsupported letterSpacing in {name}")),
            };
            let weight = style["fontWeight"]
                .as_u64()
                .unwrap_or_else(|| panic!("tokens.json: fontWeight in {name}"));
            writeln!(
                out,
                "/// {usage}\npub const {constant}: TextToken = TextToken {{ family: Family::{family}, size: {size:?}, line_height: {line:?}, weight: {weight}, letter_spacing: {spacing:?} }};",
                usage = text(&style["usage"], "usage"),
                constant = ident(name).to_uppercase(),
                size = px(text(&style["fontSize"], "fontSize")),
                line = px(text(&style["lineHeight"], "lineHeight")),
            )
            .unwrap();
        }
    }
    out.push('\n');
}

fn lengths(tokens: &Value, group: &str, out: &mut String) {
    for token in list(tokens, group, "tokens") {
        writeln!(
            out,
            "/// {usage}\npub const {constant}: f32 = {value:?};",
            usage = text(&token["usage"], "usage"),
            constant = ident(text(&token["name"], "token name")).to_uppercase(),
            value = px(text(&token["value"], "length")),
        )
        .unwrap();
    }
    out.push('\n');
}

/// Splits a CSS list on the commas that are not inside parentheses.
fn split_top_level(css: &str) -> Vec<&str> {
    let mut parts = Vec::new();
    let (mut depth, mut start) = (0usize, 0usize);
    for (index, character) in css.char_indices() {
        match character {
            '(' => depth += 1,
            ')' => depth = depth.saturating_sub(1),
            ',' if depth == 0 => {
                parts.push(css[start..index].trim());
                start = index + 1;
            }
            _ => {}
        }
    }
    parts.push(css[start..].trim());
    parts
}

/// One layer such as `inset 0 2px 5px rgba(0, 0, 0, 0.6)` or `0 3px 0 #B9B2A4`:
/// `[inset] x y blur [spread] colour`.
fn shadow_layer(css: &str) -> String {
    let (inset, rest) = match css.strip_prefix("inset ") {
        Some(rest) => (true, rest.trim()),
        None => (false, css),
    };
    let colour_at = rest
        .find("rgba(")
        .or_else(|| rest.find('#'))
        .unwrap_or_else(|| panic!("unsupported shadow {css}"));
    let (offsets, colour) = rest.split_at(colour_at);
    let numbers: Vec<f64> = offsets
        .split_whitespace()
        .map(|part| if part == "0" { 0.0 } else { px(part) })
        .collect();
    assert!(
        numbers.len() == 3 || numbers.len() == 4,
        "unsupported shadow {css}"
    );
    format!(
        "ShadowToken {{ x: {:?}, y: {:?}, blur: {:?}, spread: {:?}, color: {:#010x}, inset: {inset} }}",
        numbers[0],
        numbers[1],
        numbers[2],
        numbers.get(3).copied().unwrap_or(0.0),
        rgba(colour)
    )
}

fn shadows(tokens: &Value, out: &mut String) {
    out.push_str(
        "/// One layer of a box shadow. Offsets, blur and spread are in pixels; the colour is 0xRRGGBBAA.\n#[derive(Debug, Clone, Copy, PartialEq)]\npub struct ShadowToken {\n    pub x: f32,\n    pub y: f32,\n    pub blur: f32,\n    pub spread: f32,\n    pub color: u32,\n    pub inset: bool,\n}\n\n",
    );
    for token in list(tokens, "shadow", "tokens") {
        let name = text(&token["name"], "shadow name");
        // A string is the same in both themes; otherwise one value per theme.
        let layers = THEMES.map(|theme| {
            let css = match &token["value"] {
                Value::String(css) => css.as_str(),
                value => text(&value[theme], &format!("shadow {name}.{theme}")),
            };
            split_top_level(css)
                .into_iter()
                .map(shadow_layer)
                .collect::<Vec<_>>()
        });
        writeln!(
            out,
            "/// {} As `[dark, light]`, each a list of layers drawn first to last.\npub const {}: [&[ShadowToken]; 2] = [",
            text(&token["usage"], "usage"),
            ident(name).to_uppercase()
        )
        .unwrap();
        for theme in layers {
            writeln!(out, "    &[{}],", theme.join(", ")).unwrap();
        }
        out.push_str("];\n");
    }
}
